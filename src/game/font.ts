export function hasGlyph(char: string): boolean {
  return GLYPHS[char] !== undefined;
}

export function measureText(text: string, scale: number, tracking = 0): number {
  const length = text.length;
  if (length === 0) return 0;
  return (length * GLYPH_W + (length - 1) * (GAP + tracking)) * scale;
}

export interface TextStyle {
  x: number;
  y: number;
  scale: number;
  color: string;
  /** Big text needs it: a scaled-up drop shadow otherwise fills the default gap. */
  tracking?: number;
}

export type Ink = Pick<CanvasRenderingContext2D, "fillStyle" | "fillRect">;

export function drawText(ink: Ink, text: string, style: TextStyle): void {
  ink.fillStyle = style.color;
  const advance = GLYPH_W + GAP + (style.tracking ?? 0);
  for (let index = 0; index < text.length; index++) {
    const rows = GLYPHS[text.charAt(index)];
    // An unknown character (a space, most of all) is a gap of exactly one advance.
    if (rows === undefined) continue;
    rows.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) {
        if (row.charAt(rx) !== "#") continue;
        ink.fillRect(
          style.x + (index * advance + rx) * style.scale,
          style.y + ry * style.scale,
          style.scale,
          style.scale,
        );
      }
    });
  }
}
