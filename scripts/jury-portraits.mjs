for (const { file, art } of PORTRAITS) {
  if (art.length !== H) {
    throw new Error(`${file} is ${art.length} rows tall, not ${H}`);
  }
  for (const [at, row] of art.entries()) {
    if (row.length !== W) {
      throw new Error(`${file} row ${at} is ${row.length} wide, not ${W}`);
    }
  }
}

const INDEX_OF = new Map(PALETTE.map((entry, index) => [entry.key, index]));

function raster(art, file) {
  return art.map((line, y) =>
    Array.from(line, (key, x) => {
      const index = INDEX_OF.get(key);
      if (index === undefined) {
        throw new Error(`${file} uses "${key}" at ${String(x)},${String(y)}`);
      }
      return index;
    }),
  );
}

mkdirSync(OUT, { recursive: true });
for (const { file, art } of PORTRAITS) {
  const bytes = png(raster(art, file), PALETTE);
  writeFileSync(path.join(OUT, file), bytes);
  process.stdout.write(
    `${file}: ${W}x${H}, ${(bytes.length / 1024).toFixed(1)} KB\n`,
  );
}
